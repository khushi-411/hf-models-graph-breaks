"""Write an "Affected models in this sweep" table into every issue draft.

    python -m graph_breaks.affected          # rewrites the generated section in issues/**/*.md

For each root cause in known_issues.yaml, collects every run in the result directories listed in coverage.SOURCES (static,
dynamic and dynamic --unbacked; CPU and CUDA) where it shows up:
  - graph breaks matched to the issue (same matcher as summarize.py / coverage.py),
  - crashes attributed to it (coverage.ERROR_CAUSES),
  - dynamic-shape recompiles whose guards or Inductor specializations carry its signature (RECOMPILE_SIGNS).

The table goes between AFFECTED_START / AFFECTED_END markers at the end of the draft. Drafts that already have a
hand-written section marked with MANUAL are left alone.
"""

from __future__ import annotations

import json
import re
from collections import OrderedDict, defaultdict
from pathlib import Path

import yaml

from graph_breaks.coverage import SOURCES, _breaks, _error_cause
from graph_breaks.summarize import issue_label, load_known_issues, match_issue

ROOT = Path(__file__).resolve().parent.parent
AFFECTED_START = "<!-- affected-models:start (generated by `python -m graph_breaks.affected`, do not edit) -->"
AFFECTED_END = "<!-- affected-models:end -->"
# Put this right above a hand-written "### Affected models" section to keep the generator away from the draft.
MANUAL = "<!-- affected-models:manual -->"
SCENARIO = {"eval_forward": "eval", "eval_with_cache": "cache", "train_forward": "train"}

# Recompile-only root causes: substrings searched in a dynamic run's recompile reasons and in the sites/examples
# of its Inductor specialization events. A hit on a run that recompiles counts as affected; a hit on a run that
# doesn't recompile is shown as "guard only".
RECOMPILE_SIGNS = {
    "conv-backward-stride-guard": ["convolution_backward_lowering"],
    "cpp-acc-helper-reduction-guard": ["need_use_acc_helper"],
    "significant-strides-equal-guard": ["significant_strides_equal"],
    "mamba-associative-scan-seq-guard": ["associative_scan"],
    "nemotron-h-pad-size-guard": ["if pad_size > 0"],
    "sdpa-efficient-backward-bias-align-guard": ["meta__scaled_dot_product_efficient_backward", "meta__efficient_attention_backward"],
    "one-hot-num-classes-symint": ["nn.functional.one_hot("],
    "native-eager-router-traced-by-dynamo": ["eager_router"],
    "dynamo-unknown-stride-guard-source": ["unknown source"],
    "placeholder-check-fstring-symint": ["do not match, tokens:"],
    "detr-mask-interpolate-batch-as-channels": ["_upsample_nearest"],
    "python-loop-over-seq-len": ["range(num_blocks)", "range(seq_length)"],
    "levit-attention-bias-cache": ["attention_bias_cache"],
}
# Crashes / cancelled runs whose stored error text names a compile-time root cause.
ERROR_SIGNS = {
    "inductor-cpu-tiling-stride-at-simplify": ["Not run to completion: CPU dynamic compile cancelled", "did not finish within 2 h on CPU"],
}
# Root causes with nothing in the stored results to match on: say why instead of an empty table.
NO_RESULT_NOTE = {
    "problem-type-config-mutation": "The harness pre-sets `config.problem_type` (see `graph_breaks/dynamic.py`) so the "
    "recompile doesn't show up in the stored runs. Every `*ForSequenceClassification` / `*ForImageClassification` model "
    "trained with `problem_type=None` is affected (seen by hand: vit).",
    "output-capturing-reconstruction": "0 occurrences with transformers `b7fe69cb19`. Seen earlier with transformers 5.22.1 "
    "in opt and bart train (after the LayerDrop break).",
    "inductor-cpu-tiling-stride-at-simplify": "The table only has the CPU runs that were cancelled. Also slow on CPU "
    "in the hand measurements above, but with a stored result: gemma3_vlm (1 h 02 min) and mobilevit "
    "(> 2 h 50 min in one attempt; the stored run finished).",
    "tolist-unbacked-length": "Only shows up with `capture_scalar_outputs=True` + `capture_dynamic_output_shape_ops=True`, "
    "which the harness doesn't set, so no stored run has it. Checked by hand: qwen2_5_vl and qwen3_vl (compile "
    "fails instead of graph-breaking).",
    "floordiv-simplify-compile-time": "Compile time isn't stored in the results. Measured by hand: swin (CUDA eval 15.5 min, "
    "train 52 min; CPU eval > 25 min, stopped). See the table above.",
}


def _hf_ids() -> dict[str, str]:
    data = yaml.safe_load((ROOT / "models.yaml").read_text())
    return {m["name"]: m.get("hf_id", "") for m in data.get("models", [])}


def _sizes(r: dict) -> str:
    return " / ".join(str(x["new_graphs"]) for x in r.get("runs", []))


def collect() -> tuple[dict, dict]:
    """issue id -> model -> (check, device) -> [cell texts]"""
    issues = load_known_issues()
    by_id = OrderedDict()
    for i in issues:
        by_id.setdefault(i["id"], i)
    hits: dict = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))
    for (check, device), d in SOURCES.items():
        for f in sorted((ROOT / d).glob("*/*.json")):
            r = json.loads(f.read_text())
            model, sc = r["model"], SCENARIO.get(r["scenario"], r["scenario"])
            if r["status"] != "ok":
                text = (r.get("error") or "") + "\n" + (r.get("traceback") or "")
                cause, _ = _error_cause(r, by_id)
                for iid, issue in by_id.items():
                    if cause == issue_label(issue) or any(s in text for s in ERROR_SIGNS.get(iid, [])):
                        what = "not finished (compile cancelled)" if "Not run" in text or "within 2 h" in text else "**crash**"
                        hits[iid][model][(check, device)].append(f"{sc}: {what}")
                continue
            counts: dict[str, int] = defaultdict(int)
            for b in _breaks(r):
                i = match_issue(b, issues)
                if i is not None:
                    counts[i["id"]] += b.get("count", 1)
            for iid, n in counts.items():
                hits[iid][model][(check, device)].append(f"{sc} {n}")
            if check != "static":
                blob = "\n".join(r.get("recompile_reasons") or []) + json.dumps(
                    [e for e in r.get("events", []) if e.get("kind") == "specialize"])
                for iid, signs in RECOMPILE_SIGNS.items():
                    if iid in counts or not any(s in blob for s in signs):
                        continue
                    if r.get("recompiled_graphs"):
                        hits[iid][model][(check, device)].append(f"{sc}: recompiles ({_sizes(r)})")
                    else:
                        hits[iid][model][(check, device)].append(f"{sc}: guard only ({_sizes(r)})")
    return by_id, hits


def section(iid: str, models: dict, hf: dict) -> str:
    L = [AFFECTED_START, "", "### Affected models in this sweep", ""]
    if not models:
        L += [NO_RESULT_NOTE.get(iid, "No stored run matches this root cause."), "", AFFECTED_END]
        return "\n".join(L)
    L += [f"{len(models)} model(s). Each cell lists the scenarios where this root cause shows up: a number is the "
          "graph breaks matched to it in that run; `recompiles (a / b / c)` is graphs compiled on the 1st / 2nd / 3rd "
          "input size with `dynamic=True`; `guard only` means the guard was installed but didn't fail on these sizes. "
          "Recompile counts are for the whole run, so a model with several root causes counts all of them. "
          "Scenarios: `eval` = eval_forward, `cache` = eval_with_cache, `train` = train_forward. Models are built from "
          "the checkpoint's config with reduced layers and random weights.", "",
          "| model | config from | " + " | ".join(f"{c} {d.upper()}" for c, d in SOURCES) + " |",
          "|---|---|" + "---|" * len(SOURCES)]
    for model in sorted(models):
        cells = [" · ".join(models[model].get(k, [])) or "–" for k in SOURCES]
        L.append(f"| {model} | `{hf.get(model, '') or '?'}` | " + " | ".join(cells) + " |")
    if iid in NO_RESULT_NOTE:
        L += ["", NO_RESULT_NOTE[iid]]
    L += ["", AFFECTED_END]
    return "\n".join(L)


def main() -> int:
    by_id, hits = collect()
    hf = _hf_ids()
    written = skipped = 0
    for iid, issue in by_id.items():
        path = ROOT / issue["draft"]
        text = path.read_text()
        new = section(iid, hits.get(iid, {}), hf)
        if AFFECTED_START in text:
            text = re.sub(re.escape(AFFECTED_START) + r".*?" + re.escape(AFFECTED_END), lambda _: new, text, flags=re.S)
        elif MANUAL in text:
            skipped += 1  # hand-written section
            continue
        else:
            text = text.rstrip() + "\n\n" + new + "\n"
        path.write_text(text)
        written += 1
    print(f"Wrote the affected-models section in {written} draft(s); {skipped} have a hand-written one.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
